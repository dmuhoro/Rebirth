const CRISIS_INTENT_PATTERNS = [
  /\bi\s+(?:want|plan|intend|need|am going|might|will)\s+to\s+(?:kill|hurt|harm)\s+myself\b/i,
  /\bi\s+(?:want|plan|intend|am going)\s+to\s+(?:die|end my life|take my life|commit suicide)\b/i,
  /\bi\s+(?:am\s+)?(?:planning|intending)\s+to\s+(?:kill|hurt|harm)\s+myself\b/i,
  /\bi\s+(?:am\s+)?(?:planning|intending)\s+to\s+(?:die|end my life|take my life|commit suicide)\b/i,
  /\bi\s+(?:feel|am|have been feeling)\s+suicidal\b/i,
  /\bi\s+(?:want to die|wish i were dead|wish i was dead|don't want to live|do not want to live)\b/i,
  /\bi(?:'m| am)\s+(?:having|thinking about)\s+(?:suicidal thoughts|suicide|killing myself|self[- ]harm)\b/i,
  /\bi\s+(?:am\s+)?(?:considering|thinking about)\s+(?:suicide|killing myself|ending my life|self[- ]harm)\b/i,
  /\bi\s+(?:attempted|tried(?:\s+to)?)\s+(?:kill myself|end my life|commit suicide|suicide)\b/i,
];

export function detectsImmediateCrisisRisk(text: string): boolean {
  return CRISIS_INTENT_PATTERNS.some((pattern) => pattern.test(text));
}

